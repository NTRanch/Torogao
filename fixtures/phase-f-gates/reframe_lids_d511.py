#!/usr/bin/env python3
"""D-511 governed rig change: the eyelid re-frame.

Owner decision D-511 (2026-11-02) authorises shifting the
eyelid coupling frame on the three cast rigs so the
repertoire lids land in the coupling table's frame
(RIG-TEMPLATE §2, FR-07: aperture A(R) at the nodes
R = 0.3/0.5/0.8/1.0 is 0.78/0.69/0.58/0.52).

Measured evidence (T2-REPORT, G-07; re-measured at full
precision before this change): on all three rigs the
evaluated aperture sat a constant fraction below the
table at every node — offsets [0.2133, 0.2122, 0.2108,
0.2101], mean 0.21158 — with the coupling *shape* exact
(node deltas to ±0.002). The evaluated eye height is
H = 10.125 world units on all three rigs, so the frame
offset in rig units is:

    delta = 0.21158 x 10.125 = 2.1422 world units

(per-rig measurement: prima 2.1422, yui 2.1422, alma
2.1422 — the three rigs share the template geometry, so
the measured per-rig offsets coincide.)

The change: in each rig's payload, the ParamEyeRoll
bindings on the UpperLidL / UpperLidR parts carry
per-keyform vertex offsets [0, dy] with dy =
[0.0, 0.7, 1.6, 2.7, 3.3] at the axis points
[0.0, 0.3, 0.5, 0.8, 1.0]. Every keyform's dy — the
R = 0 keyform included — is shifted by -delta, raising
the lid band by exactly the measured offset at every R.
The offset only: no keyform is reshaped, the iris
bindings and every other value in the file are
untouched, and the TEX/EXT sections are copied
verbatim. Payload surgery is byte-safe: this script
refuses any file whose payload JSON does not round-trip
byte-identically before the change, and re-verifies the
round-trip after it.

Apply to the canonical corpus rigs and to the Phase D
fixture (the same rig data); the Phase F repertoire
fixtures are then regenerated by make_repertoire.py,
whose byte-faithfulness gate re-proves the chain.

Usage: reframe_lids_d511.py <inx-file> [<inx-file> ...]
The pre-frame keyform vector is asserted, so the script
refuses a file that is not in the expected pre-frame
state (it cannot be applied twice).
"""
import hashlib
import json
import struct
import sys
from pathlib import Path

# The measured frame offset in world units (see header).
DELTA = 2.1422

# The pre-frame ParamEyeRoll lid keyform dy vector.
PRE_FRAME_DY = [0.0, 0.7, 1.6, 2.7, 3.3]

LID_NAMES = ("UpperLidL", "UpperLidR")


def load_payload(raw: bytes):
    assert raw[:8] == b"TRNSRTS\x00", "bad magic"
    (payload_len,) = struct.unpack(">I", raw[8:12])
    payload_raw = raw[12 : 12 + payload_len]
    payload = json.loads(payload_raw)
    tail = raw[12 + payload_len :]
    redump = json.dumps(payload, separators=(",", ":")).encode()
    assert redump == payload_raw, "payload JSON does not round-trip byte-identically"
    return payload, tail


def lid_node_uuids(payload) -> dict:
    found = {}

    def walk(node):
        name = node.get("name")
        if name in LID_NAMES:
            found[name] = node["uuid"]
        for child in node.get("children", []) or []:
            walk(child)

    walk(payload["nodes"])
    assert set(found) == set(LID_NAMES), f"lid nodes not found: {sorted(found)}"
    return found


def shift_keyforms(binding, delta: float) -> list:
    """Shift every vertex y in every keyform of one
    binding by -delta; return the per-keyform dy vector
    (all vertices share one dy per keyform here)."""
    dys = []
    for keyform in binding["values"]:
        keyform_dys = set()
        for y_point in keyform:
            for vertex in y_point:
                assert vertex[0] == 0, f"lid coupling is not pure-vertical: {vertex}"
                vertex[1] -= delta
                keyform_dys.add(round(vertex[1], 9))
        assert len(keyform_dys) == 1, f"keyform vertices disagree in dy: {keyform_dys}"
        dys.append(keyform_dys.pop())
    return dys


def reframe(path: Path) -> None:
    raw = path.read_bytes()
    before = hashlib.sha256(raw).hexdigest()
    payload, tail = load_payload(raw)
    uuids = lid_node_uuids(payload)
    roll = next(p for p in payload["param"] if p["name"] == "ParamEyeRoll")
    targets = [b for b in roll["bindings"] if b["node"] in uuids.values()]
    assert len(targets) == 2, f"expected 2 lid bindings, found {len(targets)}"
    for binding in targets:
        dys = [
            keyform[0][0][1] for keyform in binding["values"]
        ]
        assert len(dys) == len(PRE_FRAME_DY) and all(
            abs(dy - want) < 1e-9 for dy, want in zip(dys, PRE_FRAME_DY)
        ), f"{path}: lid keyforms not in the pre-frame state: {dys}"
    shifted = [shift_keyforms(b, DELTA) for b in targets]
    payload_bytes = json.dumps(payload, separators=(",", ":")).encode()
    out = b"TRNSRTS\x00" + struct.pack(">I", len(payload_bytes)) + payload_bytes + tail
    # Re-verify the written form before it lands.
    check, _ = load_payload(out)
    roll_after = next(p for p in check["param"] if p["name"] == "ParamEyeRoll")
    for binding in roll_after["bindings"]:
        if binding["node"] in uuids.values():
            dys = [keyform[0][0][1] for keyform in binding["values"]]
            want = [dy - DELTA for dy in PRE_FRAME_DY]
            assert all(abs(dy - w) < 1e-9 for dy, w in zip(dys, want)), dys
    path.write_bytes(out)
    after = hashlib.sha256(out).hexdigest()
    print(f"{path.name}: dy {PRE_FRAME_DY} -> {[round(d, 4) for d in shifted[0]]}")
    print(f"  sha256 {before[:16]}... -> {after[:16]}... ({len(raw)} -> {len(out)} bytes)")


def main() -> int:
    assert len(sys.argv) > 1, "usage: reframe_lids_d511.py <inx-file> [...]"
    for arg in sys.argv[1:]:
        reframe(Path(arg))
    return 0


if __name__ == "__main__":
    sys.exit(main())
